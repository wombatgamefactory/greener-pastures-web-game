/**
 * The one test ticket 25 stands on: **every move the engine offers is reachable
 * through a click path**, over a corpus of real positions from real games.
 *
 * A UI can be wrong in two directions. It can offer something illegal, which
 * the engine catches by throwing - `apply` re-validates everything, so that
 * failure mode is loud and cheap. The dangerous direction is the other one: a
 * move that is legal and simply cannot be clicked. Nothing throws, nothing
 * looks broken, and a card quietly never gets played for the rest of the
 * project. So the assertion here is coverage, checked by driving the SAME
 * resolvers the interface uses rather than by re-deriving what should be
 * clickable.
 *
 * The corpus is generated by walking games with the bots, collecting every
 * position where a decision was taken. That is deliberately not a fixture:
 * a fixture would age against the rules, and this way a card added in the sheet
 * shows up in the corpus on the next run.
 */

